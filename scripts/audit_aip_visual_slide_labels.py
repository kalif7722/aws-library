#!/usr/bin/env python3
"""Audit original AIP-C01 slide images on a GitHub runner with R2 access.

Produces spatially grouped OCR evidence to support visual-first narration.
No narration or publication is generated by this script.
"""
from __future__ import annotations

import argparse
import io
import json
import re
from datetime import datetime, timezone
from pathlib import Path

import pytesseract
import requests
from PIL import Image, ImageOps

DEFAULT_ROOT = "https://pub-a5e11688cacf4195a0d3c6afe384eb56.r2.dev/aws-genai-course-visuals"

def collect_lines(image: Image.Image) -> list[dict]:
    data = pytesseract.image_to_data(image, output_type=pytesseract.Output.DICT, config="--psm 11")
    groups = {}
    for i, value in enumerate(data["text"]):
        value = value.strip()
        if not value:
            continue
        try:
            conf = float(data["conf"][i])
        except (ValueError, TypeError):
            continue
        if conf < 32:
            continue
        key = (data["block_num"][i], data["par_num"][i], data["line_num"][i])
        entry = groups.setdefault(key, {"text": [], "x": data["left"][i], "y": data["top"][i]})
        entry["text"].append(value)
        entry["x"] = min(entry["x"], data["left"][i])
        entry["y"] = min(entry["y"], data["top"][i])
    results = []
    for entry in groups.values():
        text = " ".join(entry["text"])
        if len(text) > 2:
            results.append({"x": round(entry["x"] / image.width, 3),
                            "y": round(entry["y"] / image.height, 3),
                            "text": text})
    return sorted(results, key=lambda x: (round(x["y"] / 0.035), x["x"]))

def audit(module: str, first: int, last: int, root: str):
    session = requests.Session()
    output = {"module": module, "first_slide": first, "last_slide": last,
              "created_utc": datetime.now(timezone.utc).isoformat(),
              "source": root + "/module-" + module + "/slide-NN.webp",
              "note": "Automated spatial OCR is an aid, not a substitute for visual QA. Titles/labels are not guaranteed exact.",
              "slides": []}
    for number in range(first, last+1):
        filename = f"slide-{number:02}.webp"
        candidates = [f"module-{module}/{filename}", f"module-{module}/module-{module}/{filename}"]
        response = None
        actual = None
        for key in candidates:
            try:
                r = session.get(root.rstrip("/") + "/" + key, timeout=40)
            except requests.RequestException:
                continue
            if r.ok and r.headers.get("content-type", "").startswith("image/"):
                response = r
                actual = key
                break
        if response is None:
            output["slides"].append({"slide": number, "status": "unavailable", "candidates": candidates})
            print(f"slide {number:02}: UNAVAILABLE", flush=True)
            continue
        img = Image.open(io.BytesIO(response.content)).convert("RGB")
        lines = collect_lines(img)
        band = {"header": [], "upper": [], "lower": []}
        for line in lines:
            region = "header" if line["y"] < 0.16 else "upper" if line["y"] < 0.56 else "lower"
            band[region].append(line)
        record = {"slide": number, "status": "ok", "image": actual,
                  "image_size": [img.width, img.height],
                  "header_candidates": [l["text"] for l in band["header"][:12]],
                  "spatial_lines": band}
        output["slides"].append(record)
        print(f"slide {number:02}: OK {img.width}x{img.height}, {len(lines)} OCR lines, "
              + " / ".join(record["header_candidates"][:3]), flush=True)
    return output

def main():
    p = argparse.ArgumentParser()
    p.add_argument("--module", default="06")
    p.add_argument("--start", type=int, default=6)
    p.add_argument("--end", type=int, default=24)
    p.add_argument("--root", default=DEFAULT_ROOT)
    p.add_argument("--output", required=True)
    args = p.parse_args()
    if args.start < 1 or args.end < args.start:
        raise SystemExit("Invalid range")
    obj = audit(args.module, args.start, args.end, args.root)
    dest = Path(args.output)
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(json.dumps(obj, indent=2, ensure_ascii=False) + "\n")
    failures = [s["slide"] for s in obj["slides"] if s["status"] != "ok"]
    if failures:
        raise SystemExit(f"Unreachable source slides: {failures}")

if __name__ == "__main__":
    main()
